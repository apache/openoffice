# usage: refresh_config_guess.sh <dir holding current config.guess and config.sub>
# Run in an external's configure directory; replaces every bundled copy beneath it.
find . \( -name config.guess -o -name config.sub \) -print | while read f; do
    cp "$1/${f##*/}" "$f" || exit 1
done
